# --- Імпорт стандартних бібліотек ---
import tkinter as tk                          # Основна бібліотека для GUI (графічний інтерфейс)
from tkinter import scrolledtext, ttk        # scrolledtext — текстове поле зі скролом; ttk — сучасні віджети
import threading                              # Для запуску запитів до AI у фоновому потоці (щоб GUI не зависав)
import datetime                               # Для відображення часу повідомлень
import os                                     # Для роботи з операційною системою (зчитування env-змінних)

# --- Імпорт бібліотеки Google Gemini AI ---
# Встановити командою: pip install google-generativeai
try:
    import google.generativeai as genai       # Офіційний SDK Google для Gemini
    GEMINI_AVAILABLE = True                   # Прапорець: бібліотека знайдена
except ImportError:
    GEMINI_AVAILABLE = False                  # Прапорець: бібліотека НЕ знайдена, працюємо без AI


# ============================================================
# КЛАС ТАНКОВОГО ЧАТ-БОТА
# Містить всю логіку: налаштування AI, обробку повідомлень, GUI
# ============================================================
class TankChatBot:
    def __init__(self, root):
        # root — головне вікно tkinter, яке передається при створенні об'єкта
        self.root = root
        self.root.title("🛡 Танковий Чат-Бот | Від WWI до сьогодні")  # Заголовок вікна
        self.root.geometry("900x700")                                   # Розмір вікна: 900x700 пікселів
        self.root.configure(bg="#1a1a2e")                               # Темно-синій фон (колір нічного неба)
        self.root.minsize(700, 500)                                     # Мінімальний розмір вікна

        # --- Налаштування Gemini AI ---
        self.model = None                     # Змінна для зберігання моделі Gemini (спочатку None)
        self.chat_session = None              # Змінна для сесії чату (зберігає історію розмови)
        self.setup_gemini()                   # Викликаємо метод налаштування Gemini

        # --- Будуємо інтерфейс ---
        self.setup_gui()                      # Викликаємо метод побудови GUI

        # --- Вітальне повідомлення від бота ---
        self.show_welcome()                   # Показуємо привітання при запуску


    # --------------------------------------------------------
    # МЕТОД: Налаштування Google Gemini AI
    # --------------------------------------------------------
    def setup_gemini(self):
        if not GEMINI_AVAILABLE:
            # Якщо бібліотека не встановлена — пропускаємо
            return

        # Отримуємо API ключ: спочатку з змінної середовища, потім з константи
        # РЕКОМЕНДОВАНО: встановіть змінну середовища GEMINI_API_KEY
        # Команда в терміналі (Windows): set GEMINI_API_KEY=ваш_ключ
        # Команда в терміналі (Mac/Linux): export GEMINI_API_KEY=ваш_ключ
        api_key = os.environ.get("GEMINI_API_KEY", "ВАШ_КЛЮЧ_GEMINI_API_ТУТ")

        if api_key == "ВАШ_КЛЮЧ_GEMINI_API_ТУТ":
            # Ключ не замінено — AI не буде працювати
            self.model = None
            return

        try:
            genai.configure(api_key=api_key)  # Передаємо API ключ у бібліотеку Gemini

            # Системна інструкція — "особистість" нашого бота
            # Вона задає контекст і стиль відповідей для Gemini
            system_instruction = """
            Ти — експерт-енциклопедист з військової техніки, спеціаліст з танків та бронетехніки.
            Твоя база знань охоплює всі танки та бронемашини від Першої світової війни (1916) до сьогодні.
            
            Ти знаєш:
            - WWI: Mark I-V (Велика Британія), A7V (Німеччина), Schneider CA1, Saint-Chamond (Франція)
            - WWII: Т-34, КВ-1, ІС-2 (СРСР), Tiger I/II, Panzer III/IV, Panther (Німеччина), 
                    Sherman, Pershing (США), Churchill, Cromwell (Велика Британія), Char B1 (Франція)
            - Холодна війна: Т-54/55, Т-62, Т-64, Т-72 (СРСР), M48, M60 Patton (США), 
                             Leopard 1 (Німеччина), Centurion (Велика Британія), AMX-30 (Франція)
            - Сучасні: Т-80, Т-90, Армата Т-14 (Росія), M1 Abrams (США), Leopard 2 (Німеччина),
                       Challenger 2 (Велика Британія), Leclerc (Франція), Merkava (Ізраїль),
                       K2 Black Panther (Корея), Type 99 (Китай), Оплот, БМ Булат (Україна)
            
            Правила відповідей:
            1. Відповідай УКРАЇНСЬКОЮ мовою
            2. Будь точним у технічних характеристиках (броня, гармата, двигун, маса, швидкість)
            3. Додавай цікаві факти та бойове застосування
            4. Якщо питання не стосується танків/бронетехніки — ввічливо поверни розмову до теми
            5. Використовуй емодзі де доречно (⚙️🛡🔫💨📊)
            6. Структуруй великі відповіді з підзаголовками
            7. Порівнюй техніку, якщо тебе про це просять
            """

            # Створюємо модель gemini-1.5-flash — швидка і безкоштовна модель Gemini
            self.model = genai.GenerativeModel(
                model_name="gemini-1.5-flash",         # Назва моделі
                system_instruction=system_instruction  # Передаємо системну інструкцію
            )

            # Починаємо нову сесію чату (вона зберігатиме всю історію діалогу автоматично)
            self.chat_session = self.model.start_chat(history=[])

        except Exception as e:
            # Якщо виникла помилка при налаштуванні — зберігаємо її текст
            print(f"Помилка Gemini API: {e}")
            self.model = None                         # Скидаємо модель до None


